"""The Legend palette registry is generated; the committed C# and the docs table must match
the generator, and the palette numbers users type must never move."""
from pathlib import Path
import importlib.util
import re
import subprocess
import sys
import unittest

ROOT = Path(__file__).resolve().parents[2]
SCRIPT = ROOT / "tools" / "gen_color_schemes.py"
DATA = ROOT / "Lugworm.Core" / "Analysis" / "ColorSchemeData.cs"
TABLE = ROOT / "docs" / "reference" / "legend-palette-table.md"

# The frozen numbering (5.0.0). Append-only: a new palette adds a line at the end; an
# existing line never changes. Editing this list is a deliberate, documented act.
FROZEN_NUMBERS = [
    "viridis", "plasma", "inferno", "magma", "cividis", "turbo", "Greys", "Blues",
    "Greens", "Oranges", "Reds", "Purples", "YlOrRd", "YlGnBu", "coolwarm", "RdBu",
    "RdYlBu", "Spectral", "PuOr", "BrBG", "PiYG", "bwr", "seismic", "RdYlGn",
    "twilight", "hsv", "rainbow", "tab10", "tab20", "Set1", "Set2", "Dark2",
    "Paired", "Okabe-Ito", "traffic",
]


class ColorSchemeSyncTests(unittest.TestCase):
    def test_generated_files_exist(self):
        self.assertTrue(DATA.exists())
        self.assertTrue(TABLE.exists())
        text = DATA.read_text(encoding="utf-8")
        self.assertIn("<auto-generated>", text)
        for owned in ("plasma", "viridis", "traffic"):     # Core owns these three
            self.assertNotIn(f'new ColorScheme("{owned}"', text)
        for name in ('"magma"', '"Blues"', '"tab10"', '"Okabe-Ito"', '"rainbow"'):
            self.assertIn("new ColorScheme(" + name, text)
        for removed in ('"npg"', '"gsea"', '"YlOrBr"', '"R4"', '"heat"'):   # 5.0.0 removals
            self.assertNotIn("new ColorScheme(" + removed, text)
        self.assertFalse((ROOT / "tools" / "color_schemes" / "ggsci.json").exists())

    def test_palette_numbers_are_frozen(self):
        text = DATA.read_text(encoding="utf-8")
        block = re.search(r"Numbered =\s*\{(.*?)\};", text, re.S).group(1)
        numbered = re.findall(r'"([^"]+)",\s*// (\d+)', block)
        names = [n for n, _ in numbered]
        self.assertEqual([str(i) for i in range(len(numbered))], [k for _, k in numbered])
        self.assertEqual(FROZEN_NUMBERS, names[:len(FROZEN_NUMBERS)],
                         "a palette number moved - numbers are append-only")
        rows = re.findall(r"^\| (\d+) \| `([^`]+)` \|", TABLE.read_text(encoding="utf-8"), re.M)
        self.assertEqual(list(enumerate(names)), [(int(k), n) for k, n in rows])

    def test_generated_file_is_current(self):
        if importlib.util.find_spec("matplotlib") is None:
            self.skipTest("matplotlib not installed - generator cannot run")
        result = subprocess.run([sys.executable, str(SCRIPT), "--check"], capture_output=True, text=True)
        self.assertEqual(0, result.returncode, result.stdout + result.stderr)


if __name__ == "__main__":
    unittest.main()
